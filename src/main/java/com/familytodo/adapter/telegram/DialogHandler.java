package com.familytodo.adapter.telegram;

/**
 * Обработчик свободного текста внутри начатого сценария.
 *
 * <p>Отличается от {@link CommandHandler} тем, что срабатывает не по команде, а по состоянию
 * диалога: бот сам спросил — значит, ждёт ответ.
 */
public interface DialogHandler {

    /**
     * Имя отличается от {@code handle} намеренно: один класс нередко и команда, и шаг сценария, а
     * два метода с одинаковой сигнатурой и разным типом возврата в Java не уживаются.
     *
     * @return {@code true}, если для этого пользователя есть активный шаг и сообщение обработано
     */
    boolean continueDialog(BotRequest request);
}
