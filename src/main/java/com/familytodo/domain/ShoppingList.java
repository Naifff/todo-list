package com.familytodo.domain;

/**
 * Какой из двух списков покупок.
 *
 * <p>Два списка — это признак у позиции, а не две сущности и не две таблицы: правила, права и
 * экраны у них совпадают полностью, различается только куда позиция попадёт. Третий список (скажем,
 * «аптека») здесь будет стоить одну строку.
 */
public enum ShoppingList {

    /** Продовольственный: молоко, хлеб, всё что кончается само. */
    FOOD,

    /** Хозяйственный: порошок, лампочки, всё что кончается незаметно. */
    HOUSEHOLD
}
