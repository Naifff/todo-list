package com.familytodo.domain;

/**
 * Цвет участника — им рисуются его дела в расписании.
 *
 * <p>В сетке на неделю колонка узкая, имя в блоке читается плохо или не помещается вовсе. Цвет
 * отвечает на вопрос «чьё это дело» с одного взгляда и не занимает места.
 *
 * <p>Палитра <b>пастельная</b>. Сначала были насыщенные цвета категорий Outlook — их подбирали под
 * ровно эту задачу, различимость плашек в календаре, — но на своей неделе они оказались слишком
 * грубыми: восемь плотных заливок на белом листе кричат громче, чем то, что на них написано.
 * Пастель тише, а различать её надо всего среди семи соседей, а не среди двадцати категорий.
 *
 * <p>⚠️ Светлая заливка тянет за собой цвет текста: на плашке он <b>тёмный</b>, а не белый (см.
 * {@code --on-plate} в CalendarHtmlRenderer). Поменять здесь hex и не поменять там — значит
 * получить белым по светло-голубому.
 *
 * <p>Порядок и имена не трогать: {@link #forMember(long)} выводит цвет из номера участника, и
 * перестановка перекрасила бы всех разом. По именам же выбраны кружки-эмодзи в сообщениях.
 *
 * <p>Цвет хранится <b>перечислением, а не hex-строкой</b>: так его можно перекрасить разом во всём
 * приложении, а в базе не окажется случайного «#ff00ff», который где-то не прочитается.
 */
public enum MemberColor {
    BLUE("Синий", "#a4c6ef"),
    RED("Красный", "#f2a6a0"),
    GREEN("Зелёный", "#aed9a0"),
    PURPLE("Фиолетовый", "#c3b2e8"),
    ORANGE("Оранжевый", "#f3c48a"),
    TEAL("Бирюзовый", "#93d2ce"),
    MAROON("Бордовый", "#d69bb8"),
    OLIVE("Оливковый", "#c2c48c");

    private final String title;
    private final String hex;

    MemberColor(String title, String hex) {
        this.title = title;
        this.hex = hex;
    }

    /**
     * Цвет по умолчанию для нового участника.
     *
     * <p>Выводится из номера, а не выдаётся по порядку выборки: иначе цвета перетасовывались бы при
     * каждом изменении состава. Первые участники семьи получают разные цвета — ради этого всё и
     * затевалось.
     */
    public static MemberColor forMember(long memberId) {
        MemberColor[] palette = values();
        int index = (int) Math.floorMod(memberId - 1, palette.length);
        return palette[index];
    }

    /** Как цвет называется человеку в списке выбора. */
    public String title() {
        return title;
    }

    /** Значение для CSS страницы расписания. */
    public String hex() {
        return hex;
    }
}
