package com.familytodo.domain;

/**
 * Цвет участника — им рисуются его дела в расписании.
 *
 * <p>В сетке на неделю колонка узкая, имя в блоке читается плохо или не помещается вовсе. Цвет
 * отвечает на вопрос «чьё это дело» с одного взгляда и не занимает места.
 *
 * <p>Палитра взята из категорий Outlook: она подобрана людьми, которые решали ровно эту задачу —
 * различимость цветных плашек в календаре, — и заодно знакома на вид. Значения соответствуют палитре
 * Microsoft Fluent, на которой построены категории; если понадобится точность до кода из конкретной
 * версии Outlook, правится ровно одна константа на цвет.
 *
 * <p>Цвет хранится <b>перечислением, а не hex-строкой</b>: так его можно перекрасить разом во всём
 * приложении, а в базе не окажется случайного «#ff00ff», который где-то не прочитается.
 */
public enum MemberColor {
    BLUE("Синий", "#0078d4"),
    RED("Красный", "#d13438"),
    GREEN("Зелёный", "#498205"),
    PURPLE("Фиолетовый", "#8764b8"),
    ORANGE("Оранжевый", "#ca5010"),
    TEAL("Бирюзовый", "#038387"),
    MAROON("Бордовый", "#a4262c"),
    OLIVE("Оливковый", "#7a7574");

    private final String title;
    private final String hex;

    MemberColor(String title, String hex) {
        this.title = title;
        this.hex = hex;
    }

    /**
     * Цвет по умолчанию для нового участника.
     *
     * <p>Выводится из номера, а не выдаётся по порядку выборки: иначе цвета перетасовывались бы при
     * каждом изменении состава. Первые участники семьи получают разные цвета — ради этого всё и
     * затевалось.
     */
    public static MemberColor forMember(long memberId) {
        MemberColor[] palette = values();
        int index = (int) Math.floorMod(memberId - 1, palette.length);
        return palette[index];
    }

    /** Как цвет называется человеку в списке выбора. */
    public String title() {
        return title;
    }

    /** Значение для CSS страницы расписания. */
    public String hex() {
        return hex;
    }
}
