-- Расписание уроков.
--
-- ⚠️ Урок — НЕ задача, и разница не в размере. У него нет исполнителя (никто не просил ребёнка
-- сделать алгебру), от него нельзя отказаться с причиной и его нельзя «сделать»: он просто идёт.
-- Шесть уроков × пять дней × тридцать пять недель — тысяча строк в год на одного ребёнка, и
-- строками task они забили бы /my, дайджест и календарь, то есть ровно те экраны, ради которых всё
-- и делалось. Отсюда своя таблица — и, как следствие, требование «в списках дел уроков нет»
-- выполняется структурно: списки выбирают из task, а уроков там не бывает.
--
-- ⚠️ Строка здесь — ПРАВИЛО, а не урок конкретного дня, и материализации у неё нет, в отличие от
-- вхождений серии. Вхождения становятся строками потому, что у каждого своя судьба: одно сделано,
-- другое отклонено с причиной. У урока судьбы нет — он либо в расписании, либо нет, — поэтому
-- конкретный день получается наложением правила на дату при отрисовке окна.
--
-- Звонков в схеме нет намеренно: они живут в самом сообщении, которым заводят расписание, и нужны
-- только чтобы расставить предметы по позициям. Сюда уезжает уже конкретное время.

create table lesson (
    id          integer primary key,
    family_id   integer not null references family (id),
    member_id   integer not null references member (id),
    -- номер дня ISO: 1 — понедельник
    day_of_week integer not null check (day_of_week between 1 and 7),
    -- HH:MM по календарю семьи, как start_time у серии: момент считается при отрисовке
    starts_at   text    not null,
    ends_at     text    not null,
    subject     text    not null check (length(subject) between 1 and 60),
    -- срок действия: летом расписание не показывается, но и не стирается
    valid_from  text    not null,                -- YYYY-MM-DD
    valid_to    text,                            -- null: без конца
    created_at  integer not null
);

-- Выборка всегда «расписание этого ребёнка в этой семье»: family_id первым, как и у задач.
create index idx_lesson_member on lesson (family_id, member_id);

insert into id_sequence (name, next_value) values ('lesson', 0);
