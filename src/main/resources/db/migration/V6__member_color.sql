-- Цвет участника: им рисуются его дела в расписании.
--
-- В сетке на неделю колонка узкая, имя в блоке читается плохо или не влезает
-- вовсе. Цвет отвечает «чьё это дело» с одного взгляда и не занимает места.
--
-- Хранится именем из перечисления, а не hex-строкой: палитру можно поменять
-- разом, и в базе не окажется случайного «#ff00ff», который где-то не
-- прочитается.

alter table member add column color text;

-- Уже заведённым участникам цвет раздаётся тем же правилом, что и новым:
-- по номеру, а не по порядку выборки. Иначе цвета перетасовывались бы при
-- каждом изменении состава семьи.
update member
set color = case ((id - 1) % 8)
    when 0 then 'BLUE'
    when 1 then 'RED'
    when 2 then 'GREEN'
    when 3 then 'PURPLE'
    when 4 then 'ORANGE'
    when 5 then 'TEAL'
    when 6 then 'MAROON'
    else 'OLIVE'
end
where color is null;
