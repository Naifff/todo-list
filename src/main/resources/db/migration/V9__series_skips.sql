-- Пропущенный день серии.
--
-- Повод бытовой: «в эту пятницу тренировки не будет». Человек открывает вхождение и жмёт
-- «Удалить» — самый естественный жест, и до сих пор он обманывал. Строка стиралась, а джоба
-- материализации раз в час спрашивает у базы, каких дат не хватает, и создавала вхождение
-- заново. Дело возвращалось, и понять почему по экрану было нельзя.
--
-- Помнить пропуск больше негде: удаление у нас жёсткое, статуса DELETED нет сознательно, а
-- уникальный индекс (series_id, occurrence_on) после удаления строки ничего не держит. Отсюда
-- отдельная таблица: единственное её дело — сказать джобе «этот день не восстанавливать».
--
-- Заполняется она в JdbcTaskRepository.delete, в одной транзакции с удалением строки. Не в
-- юзкейсе: тогда пропуск зависел бы от того, помнит ли о нём вызывающий, а забыть его — значит
-- вернуть ровно ту ошибку, ради которой таблица заведена.

create table task_series_skip (
    series_id     integer not null references task_series (id) on delete cascade,
    occurrence_on text    not null,
    primary key (series_id, occurrence_on)
);

-- ⚠️ Колонки «когда пропустили» здесь НЕТ намеренно. Заполнить её честно нечем: удаление идёт
-- через репозиторий, у которого нет часов, а Instant.now() в коде — ровно то, что в этом проекте
-- запрещено (иначе границу суток и переход на летнее время проверить нечем). Колонка, которую
-- никто не читает и некому заполнить, хуже её отсутствия.
--
